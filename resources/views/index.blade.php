									<h2 class="heading__title text-center"><span>About the Project</span></h2>
								</div>
								
								<p>The DECODE is a project led by the <a style="color: inherit" href="https://www.unescochair-cbrsr.org/" target="_blank">UNESCO Chair for Community-Based Research and Social Responsibility in Higher Education</a> and funded by the International Development Research Centre (IDRC).</p>
								<p>Our world today encounters pressing challenges like climate crises and persistent inequalities. To advance and address the complexities faced by humanity, new knowledge is imperative. However, a crucial question arises: What knowledge? Whose knowledge? Are there new understandings of knowledge? What about previously ignored or rejected systems of knowledge?</p>
                <p>In response, the DECODE project takes centre stage, with its primary goal to enhance the potential of locally contextualized actionable knowledge to address challenges identified by communities. Framed within a gender and decolonial lens, the project is built on theoretical understandings led by Tandon and Hall on knowledge democracy and recognition of community knowledge cultures.</p>
                <p>Through a collaborative process of peer learning, collective reflections, and systematization, the project brings together the co-chairs of the UNESCO Chair in CBRSR and the Knowledge for Change Consortium. This collaboration extends to global networks of community, academically trained professionals, and Indigenous-led research practitioners, enriching our understanding of the principles, policy implications, and supportive infrastructures necessary for advancing community and Indigenous-led knowledge movements.</p>
                <p>In this journey, we explore, learn, and contribute to the advancement of community and Indigenous-led knowledge movements worldwide. Together, we can shape a future where knowledge catalyses positive change.</p>
