									<h2 class="heading__title"><span>About Us</span></h2>
								</div>
								
								<p>Drs. Rajesh Tandon and Budd Hall have been part of the critique of dominant approaches to knowledge production since the mid-1970s. They founded participatory research movement in the late 1970s, which grew from knowledge activists in the Global South into a worldwide discourse. They have led the critical movement that calls for community-based structures, movements, and organisations to take the lead in knowledge production to create locally actionable knowledge to address concerns at a local level. Between the two of them, they have published more than 200 articles and various books on the subject.</p>
								<p>The UNESCO Chair supports North-South-South and South-South partnerships that build on and enhance the emerging consensus in knowledge democracy. It strengthens recent collaboration between the Higher Education section in UNESCO, the Global University Network for Innovation (GUNI), the Global Alliance on Community University Engagement and other regional and global networks. It co-creates new knowledge through partnerships among universities (academics), communities (civil society) and government (policy makers), leading to new capacities, new solutions to pressing problems related to sustainability, social and economic disparities, cultural exclusion, mistrust and conflict; and awareness among policymakers; enhanced scholarship of engagement; and social responsibility in Higher Education.</p>
                             
